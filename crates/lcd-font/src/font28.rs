use crate::traits::{Font, GlyphLayout};

/// 16-entry blend table mapping 4-bit alpha levels (0..15) from background (0) to foreground (15) in RGB565.
#[inline(always)]
pub fn blend_lut(fg: u16, bg: u16) -> [u16; 16] {
    let fg_r = ((fg >> 11) & 0x1F) as u32;
    let fg_g = ((fg >> 5) & 0x3F) as u32;
    let fg_b = (fg & 0x1F) as u32;

    let bg_r = ((bg >> 11) & 0x1F) as u32;
    let bg_g = ((bg >> 5) & 0x3F) as u32;
    let bg_b = (bg & 0x1F) as u32;

    let mut lut = [0u16; 16];
    let mut a = 0u32;
    while a < 16 {
        let inv = 15 - a;
        let r = ((bg_r * inv + fg_r * a + 7) / 15) as u16;
        let g = ((bg_g * inv + fg_g * a + 7) / 15) as u16;
        let b = ((bg_b * inv + fg_b * a + 7) / 15) as u16;
        lut[a as usize] = (r << 11) | (g << 5) | b;
        a += 1;
    }
    lut
}

/// 28px Smooth TrueType Anti-Aliased Glyph (4-bit alpha per pixel)
#[derive(Copy, Clone, Debug)]
pub struct Glyph28 {
    pub width: u8,
    pub data: &'static [u8],
}

/// 28px Smooth Bold Anti-Aliased Numeric & Sensor Font
/// Rasterized directly from Bahnschrift/DIN TrueType vector contours with 4-bit subpixel alpha curves.
/// Supported characters: '0'..'9', '-', '.', ' ', 'm', 'A'
#[derive(Copy, Clone, Debug, Default)]
pub struct Font28;

pub static FONT_28: Font28 = Font28;

impl Font28 {
    pub const HEIGHT: u8 = 28;
    pub const LAYOUT: GlyphLayout = GlyphLayout::RowMajorNibble;

    /// Looks up glyph for character c
    pub fn glyph(&self, c: char) -> Option<&'static Glyph28> {
        get_glyph_28(c)
    }

    /// Calculates total rendered pixel width of a string in 28px font
    pub fn string_width(&self, text: &str) -> u16 {
        string_width_28(text)
    }

    /// Checks if a pixel at (px, py) is set (alpha >= 50%) for the given glyph
    pub fn is_pixel_set(&self, glyph: &Glyph28, px: u8, py: u8) -> bool {
        if px < glyph.width && py < 28 {
            let row_bytes = ((glyph.width + 1) / 2) as usize;
            let byte_idx = (py as usize) * row_bytes + (px as usize / 2);
            let b = glyph.data[byte_idx];
            let a = if (px & 1) == 0 { b >> 4 } else { b & 0x0F };
            a >= 8
        } else {
            false
        }
    }
}

impl Font for Font28 {
    #[inline(always)]
    fn width(&self) -> u8 {
        27 // Maximum proportional glyph width ('m')
    }

    #[inline(always)]
    fn height(&self) -> u8 {
        28
    }

    #[inline(always)]
    fn spacing(&self) -> u8 {
        0
    }

    #[inline(always)]
    fn contains(&self, c: char) -> bool {
        get_glyph_28(c).is_some()
    }

    #[inline(always)]
    fn char_width(&self, c: char) -> u8 {
        get_glyph_28(c).map(|g| g.width).unwrap_or(0)
    }

    #[inline(always)]
    fn string_width(&self, text: &str) -> u16 {
        string_width_28(text)
    }

    fn render_char<P: FnMut(u16)>(
        &self,
        c: char,
        fg: u16,
        bg: u16,
        mut put_pixel: P,
    ) -> Option<u8> {
        let glyph = get_glyph_28(c)?;
        let w = glyph.width;
        let lut = blend_lut(fg, bg);
        let row_bytes = ((w + 1) / 2) as usize;

        for row in 0..28 {
            let row_offset = row * row_bytes;
            let mut col = 0;
            let mut byte_idx = 0;
            while col < w {
                let b = glyph.data[row_offset + byte_idx];
                byte_idx += 1;
                let a0 = (b >> 4) as usize;
                put_pixel(lut[a0]);
                col += 1;
                if col < w {
                    let a1 = (b & 0x0F) as usize;
                    put_pixel(lut[a1]);
                    col += 1;
                }
            }
        }
        Some(w)
    }

    fn render_char_scaled<P: FnMut(u16)>(
        &self,
        c: char,
        fg: u16,
        bg: u16,
        scale: u8,
        mut put_pixel: P,
    ) -> Option<u8> {
        let glyph = get_glyph_28(c)?;
        let w = glyph.width;
        let scale = scale.max(1);
        let lut = blend_lut(fg, bg);
        let row_bytes = ((w + 1) / 2) as usize;

        for row in 0..28 {
            let row_offset = row * row_bytes;
            for _ in 0..scale {
                let mut col = 0;
                let mut byte_idx = 0;
                while col < w {
                    let b = glyph.data[row_offset + byte_idx];
                    byte_idx += 1;
                    let a0 = (b >> 4) as usize;
                    let col0 = lut[a0];
                    for _ in 0..scale {
                        put_pixel(col0);
                    }
                    col += 1;
                    if col < w {
                        let a1 = (b & 0x0F) as usize;
                        let col1 = lut[a1];
                        for _ in 0..scale {
                            put_pixel(col1);
                        }
                        col += 1;
                    }
                }
            }
        }
        Some(w * scale)
    }
}

/// Retrieves the static 28px glyph definition for character c
pub fn get_glyph_28(c: char) -> Option<&'static Glyph28> {
    match c {
        '0' => Some(&GLYPH_28_0),
        '1' => Some(&GLYPH_28_1),
        '2' => Some(&GLYPH_28_2),
        '3' => Some(&GLYPH_28_3),
        '4' => Some(&GLYPH_28_4),
        '5' => Some(&GLYPH_28_5),
        '6' => Some(&GLYPH_28_6),
        '7' => Some(&GLYPH_28_7),
        '8' => Some(&GLYPH_28_8),
        '9' => Some(&GLYPH_28_9),
        '-' => Some(&GLYPH_28_MINUS),
        '.' => Some(&GLYPH_28_DOT),
        ' ' => Some(&GLYPH_28_SPACE),
        'm' => Some(&GLYPH_28_M),
        'A' => Some(&GLYPH_28_A),
        _ => None,
    }
}

/// Computes the rendered pixel width of a string formatted in 28px font
pub fn string_width_28(text: &str) -> u16 {
    let mut total = 0u16;
    for c in text.chars() {
        if let Some(glyph) = get_glyph_28(c) {
            total += glyph.width as u16;
        }
    }
    total
}

