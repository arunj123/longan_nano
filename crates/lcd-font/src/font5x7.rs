use crate::traits::{Font, GlyphLayout};

/// Standard 5x7 ASCII Bitmap Font (ASCII 32..=126)
/// Rendered cell: 6x8 pixels (5x7 glyph + 1px right spacing column + 1px bottom spacing row)
#[derive(Copy, Clone, Debug, Default)]
pub struct Font5x7;

pub static FONT_5X7: Font5x7 = Font5x7;

impl Font5x7 {
    pub const WIDTH: u8 = 5;
    pub const HEIGHT: u8 = 7;
    pub const SPACING: u8 = 1;
    pub const CELL_WIDTH: u8 = 6;
    pub const CELL_HEIGHT: u8 = 8;
    pub const LAYOUT: GlyphLayout = GlyphLayout::ColumnMajorLsb;
    pub const FIRST_CHAR: char = ' ';
    pub const LAST_CHAR: char = '~';

    /// Looks up the 5-byte column data for character `c`.
    pub fn glyph(&self, c: char) -> Option<&'static [u8]> {
        let code = c as usize;
        if (32..=126).contains(&code) {
            let idx = (code - 32) * 5;
            Some(&FONT_5X7_RAW[idx..idx + 5])
        } else {
            None
        }
    }

    /// Checks if a pixel at (px, py) is set for the given glyph slice.
    pub fn is_pixel_set(&self, glyph: &[u8], px: u8, py: u8) -> bool {
        if px < 5 && py < 7 {
            (glyph[px as usize] & (1 << py)) != 0
        } else {
            false
        }
    }


}

impl Font for Font5x7 {
    #[inline(always)]
    fn width(&self) -> u8 {
        5
    }

    #[inline(always)]
    fn height(&self) -> u8 {
        8 // Full character cell height including bottom spacing row
    }

    #[inline(always)]
    fn spacing(&self) -> u8 {
        1
    }

    #[inline(always)]
    fn contains(&self, c: char) -> bool {
        (32..=126).contains(&(c as usize))
    }

    #[inline(always)]
    fn char_width(&self, _c: char) -> u8 {
        6 // 5px glyph + 1px spacing
    }

    fn render_char<P: FnMut(u16)>(
        &self,
        c: char,
        fg: u16,
        bg: u16,
        mut put_pixel: P,
    ) -> Option<u8> {
        let glyph = self.glyph(c)?;
        for row in 0..8 {
            for col in 0..5 {
                let pixel_set = if row < 7 {
                    (glyph[col] & (1 << row)) != 0
                } else {
                    false
                };
                put_pixel(if pixel_set { fg } else { bg });
            }
            // 1 column spacing
            put_pixel(bg);
        }
        Some(6)
    }

    fn render_char_scaled<P: FnMut(u16)>(
        &self,
        c: char,
        fg: u16,
        bg: u16,
        scale: u8,
        mut put_pixel: P,
    ) -> Option<u8> {
        let glyph = self.glyph(c)?;
        let scale = scale.max(1);
        for row in 0..8 {
            for _ in 0..scale {
                for col in 0..5 {
                    let pixel_set = if row < 7 {
                        (glyph[col] & (1 << row)) != 0
                    } else {
                        false
                    };
                    let color = if pixel_set { fg } else { bg };
                    for _ in 0..scale {
                        put_pixel(color);
                    }
                }
                // Spacing column scaled
                for _ in 0..scale {
                    put_pixel(bg);
                }
            }
        }
        Some(6 * scale)
    }
}

