use crate::traits::{Font, GlyphLayout};

/// Classic 8x16 Terminal/OLED Bitmap Font (ASCII 32..=126)
/// Rendered cell: 8x16 pixels (Row-major LSB encoding)
#[derive(Copy, Clone, Debug, Default)]
pub struct Font8x16;

pub static FONT_8X16: Font8x16 = Font8x16;

impl Font8x16 {
    pub const WIDTH: u8 = 8;
    pub const HEIGHT: u8 = 16;
    pub const SPACING: u8 = 0;
    pub const LAYOUT: GlyphLayout = GlyphLayout::RowMajorLsb;
    pub const FIRST_CHAR: char = ' ';
    pub const LAST_CHAR: char = '~';

    /// Looks up the 16-byte row data for character `c`.
    pub fn glyph(&self, c: char) -> Option<&'static [u8]> {
        let code = c as usize;
        if (32..=126).contains(&code) {
            let idx = (code - 32) * 16;
            Some(&FONT_8X16_RAW[idx..idx + 16])
        } else {
            None
        }
    }

    /// Checks if a pixel at (px, py) is set for the given glyph slice.
    pub fn is_pixel_set(&self, glyph: &[u8], px: u8, py: u8) -> bool {
        if px < 8 && py < 16 {
            (glyph[py as usize] & (1 << px)) != 0
        } else {
            false
        }
    }
}

impl Font for Font8x16 {
    #[inline(always)]
    fn width(&self) -> u8 {
        8
    }

    #[inline(always)]
    fn height(&self) -> u8 {
        16
    }

    #[inline(always)]
    fn spacing(&self) -> u8 {
        0
    }

    #[inline(always)]
    fn contains(&self, c: char) -> bool {
        (32..=126).contains(&(c as usize))
    }

    #[inline(always)]
    fn char_width(&self, _c: char) -> u8 {
        8
    }

    fn render_char<P: FnMut(u16)>(
        &self,
        c: char,
        fg: u16,
        bg: u16,
        mut put_pixel: P,
    ) -> Option<u8> {
        let glyph = self.glyph(c)?;
        for row in 0..16 {
            let row_byte = glyph[row];
            for col in 0..8 {
                let set = (row_byte & (1 << col)) != 0;
                put_pixel(if set { fg } else { bg });
            }
        }
        Some(8)
    }

    fn render_char_scaled<P: FnMut(u16)>(
        &self,
        c: char,
        fg: u16,
        bg: u16,
        scale: u8,
        mut put_pixel: P,
    ) -> Option<u8> {
        let glyph = self.glyph(c)?;
        let scale = scale.max(1);
        for row in 0..16 {
            let row_byte = glyph[row];
            for _ in 0..scale {
                for col in 0..8 {
                    let set = (row_byte & (1 << col)) != 0;
                    let color = if set { fg } else { bg };
                    for _ in 0..scale {
                        put_pixel(color);
                    }
                }
            }
        }
        Some(8 * scale)
    }
}

